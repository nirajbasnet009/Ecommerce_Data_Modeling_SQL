-- Q19: How many orders were placed by customers in each state?


	SELECT customer_state, count(order_id) AS total_orders
	FROM olist_orders_dataset o
	INNER JOIN olist_customers_dataset c
		 ON o.customer_id = c.customer_id
	GROUP BY customer_state
	ORDER BY total_orders DESC;


-- Q20. How many items were purchased in each order?


	SELECT
		o.order_id,
		COUNT(oi.order_item_id) AS total_items
	FROM olist_orders_dataset o 
	INNER JOIN olist_order_items_dataset oi
		  ON o.order_id = oi.order_id
	GROUP BY o.order_id
	ORDER BY total_items DESC LIMIT 10;


-- What is the total merchandise revenue generated by Olist?

	SELECT
		SUM(price) as total_revenue
	FROM olist_order_items_dataset;
    

-- What is the total merchandise value of delivered orders?


	SELECT
		 SUM(oi.price) as delivered_merchandise_value
	FROM olist_orders_dataset o
	INNER JOIN olist_order_items_dataset oi
		 ON o.order_id = oi.order_id
	WHERE 
		 o.order_status = 'delivered';
     

-- Which 10 product categories generated the highest merchandise sales value from delivered orders?


	SELECT
		 p.product_category_name,
		 SUM(oi.price) as total_sales
	FROM olist_orders_dataset o
	INNER JOIN olist_order_items_dataset oi
		 ON o.order_id = oi.order_id
	INNER JOIN olist_products_dataset p
		 ON oi.product_id = p.product_id
	WHERE o.order_status = 'delivered'
	GROUP BY 
		  p.product_category_name
	ORDER BY
		  total_sales DESC
	LIMIT 10;
    

-- Q24. Which 10 sellers generated the highest merchandise sales value from delivered orders?


	SELECT
		 s.seller_id AS seller_id,
		 s.seller_state AS seller_state,
		 SUM(oi.price) AS total_sales
	FROM olist_orders_dataset o
	INNER JOIN olist_order_items_dataset oi
		 ON o.order_id = oi.order_id
	INNER JOIN olist_sellers_dataset s
		 ON oi.seller_id = s.seller_id
	WHERE 
		 o.order_status = 'delivered'
	GROUP BY 
		   s.seller_id,s.seller_state
	ORDER BY 
		   total_sales DESC
	LIMIT 10;


-- Which 10 Brazilian states generated the highest merchandise sales value from delivered orders?


	SELECT
		 c.customer_state AS customer_state,
		 SUM(oi.price) AS total_sales
	FROM olist_customers_dataset c
	INNER JOIN olist_orders_dataset o
		 ON c.customer_id = o.customer_id
	INNER JOIN olist_order_items_dataset oi
		 ON o.order_id = oi.order_id
	WHERE 
		 o.order_status = 'delivered'
	GROUP BY 
		   customer_state
	ORDER BY 
		   total_sales DESC
	LIMIT 10;
     
     
     
-- Which payment methods are used most frequently on Olist?

	SELECT
		payment_type,
		count(*) as total_payments
	FROM 
		olist_order_payments_dataset
	GROUP BY 
		   payment_type
	ORDER BY 
		   total_payments DESC;


-- What is the average merchandise value per delivered order?
	WITH order_totals AS (
	SELECT
		 order_id,
		 SUM(price) as order_total
	FROM olist_order_items_dataset
	GROUP BY 
		   order_id
					 )
	SELECT
		  ROUND(AVG(order_total),2) as average_order_value
	FROM order_totals ot
	INNER JOIN olist_orders_dataset o
	ON ot.order_id = o.order_id

	WHERE
		 o.order_status = 'delivered';
         
         
-- Which payment methods generated the highest total payment value?

	SELECT
		  payment_type as payment_type,
		  SUM(payment_value) as total_payment_value

	FROM olist_order_payments_dataset
	GROUP BY
		   payment_type
	ORDER BY
		   total_payment_value DESC;
           

-- What is the average delivery time for successfully delivered orders?
 
SELECT
		ROUND(AVG(TIMESTAMPDIFF(DAY,order_purchase_timestamp,order_delivered_customer_date)),2) AS average_delivery_time
FROM 
    olist_orders_dataset
WHERE 
	order_status = 'delivered'
    AND order_delivered_customer_date IS NOT NULL AND order_purchase_timestamp IS NOT NULL;
              
              
              
-- What percentage of delivered orders arrived on or before their estimated delivery date?
 

	SELECT
		 ROUND(SUM(CASE 
				WHEN (DATE(order_delivered_customer_date) <= DATE(order_estimated_delivery_date)) THEN 1 ELSE 0 END) * 100 / COUNT(*),2) AS on_time_delivery_percentage
	FROM 
		olist_orders_dataset
	WHERE 
		order_status = 'delivered'
		AND order_delivered_customer_date IS NOT NUll
		AND order_estimated_delivery_date IS NOT NULL;


     
